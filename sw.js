const SCOPE = new URL(self.registration.scope);
const SHELL_URLS = new Set(ESSENTIAL.map((file) => new URL(file, SCOPE).toString()));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Only activate a complete release. Wait for every write before cleaning a failed install.
    const results = await Promise.allSettled(ESSENTIAL.map(async (file) => {
      const response = await fetch(new URL(file, SCOPE), { cache: 'reload', ...(RELEASE_INTEGRITY[file] ? { integrity: RELEASE_INTEGRITY[file] } : {}) });
      if (!response.ok) throw new Error('Shell asset unavailable: ' + file);
      await cache.put(new URL(file, SCOPE).toString(), response);
    }));
    const failure = results.find((result) => result.status === 'rejected');
    if (failure) {
      await caches.delete(CACHE_NAME);
      throw failure.reason;
    }
    await Promise.allSettled(OPTIONAL.map(async (file) => {
      const response = await fetch(new URL(file, SCOPE), { cache: 'reload' });
      if (response.ok) await cache.put(new URL(file, SCOPE).toString(), response);
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'KDSP_SHELL_VERSION' && event.ports[0]) {
    event.ports[0].postMessage({ shellVersion: CACHE_NAME });
  }
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  const relative = url.pathname.slice(SCOPE.pathname.length);
  // Do not return shell HTML for JSON, and do not duplicate bank data in CacheStorage.
  if (relative.startsWith('content/') || relative.endsWith('.json')) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Pin precached HTML and scripts together. A new release is promoted by SW activation.
    const shellUrl = new URL(url.pathname, SCOPE.origin).toString();
    const shell = SHELL_URLS.has(shellUrl);
    const cached = await cache.match(shell ? shellUrl : request);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      if (response.ok && !shell) await cache.put(request, response.clone());
      return response;
    } catch (_) {
      return new Response(request.mode === 'navigate'
        ? 'Trang này chưa được lưu để sử dụng ngoại tuyến.'
        : 'Tài nguyên chưa được lưu trên thiết bị.', {
        status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' }
      });
    }
  })());
});
